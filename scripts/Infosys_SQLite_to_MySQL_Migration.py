"""Migrate the Infosys SQLite analytics database into MySQL 8.0.

SQLite remains the canonical database generated by the Jupyter notebook.
This script creates/populates a separate MySQL analytical copy. It never drops
or truncates tables and refuses to insert into any target table that already
contains rows.

Prerequisite: pip install mysql-connector-python
Run from the folder containing Infosys_Analysis.db. The password is requested
securely at runtime and is never written to this file.
"""
from __future__ import annotations

import getpass
import sqlite3
from pathlib import Path

import mysql.connector

SCRIPT_DIR = Path(__file__).resolve().parent
_CANDIDATE_DB_PATHS = [
    SCRIPT_DIR / "Infosys_Analysis.db",
    SCRIPT_DIR.parent / "database" / "Infosys_Analysis.db",
    SCRIPT_DIR.parent / "Infosys_Analysis.db",
]
SQLITE_DB = next((p for p in _CANDIDATE_DB_PATHS if p.exists()), _CANDIDATE_DB_PATHS[1])
MYSQL_HOST = input("MySQL host [localhost]: ").strip() or "localhost"
MYSQL_PORT_TEXT = input("MySQL port [3306]: ").strip() or "3306"
MYSQL_USER = input("MySQL user [root]: ").strip() or "root"
MYSQL_DATABASE = "infosys_valuation"
MYSQL_PASSWORD = getpass.getpass("MySQL password: ")

TABLES = [
    "annual_financials",
    "annual_ratios",
    "annual_trend",
    "quality_checks",
    "source_register",
]
BATCH_SIZE = 1000


def quote_identifier(name: str) -> str:
    # Identifiers originate from the local SQLite schema, not user input.
    return "`" + name.replace("`", "``") + "`"


def mysql_type(sqlite_type: str) -> str:
    t = (sqlite_type or "").upper()
    if "INT" in t:
        return "BIGINT"
    if any(x in t for x in ("REAL", "FLOA", "DOUB")):
        return "DOUBLE"
    if any(x in t for x in ("NUM", "DEC")):
        return "DECIMAL(30,8)"
    if "BLOB" in t:
        return "LONGBLOB"
    return "LONGTEXT"


def main() -> None:
    if not SQLITE_DB.exists():
        raise FileNotFoundError(f"SQLite database not found: {SQLITE_DB}")
    try:
        port = int(MYSQL_PORT_TEXT)
    except ValueError as exc:
        raise ValueError("MySQL port must be an integer.") from exc

    sqlite_conn = sqlite3.connect(f"file:{SQLITE_DB.as_posix()}?mode=ro", uri=True)
    mysql_conn = mysql.connector.connect(
        host=MYSQL_HOST,
        port=port,
        user=MYSQL_USER,
        password=MYSQL_PASSWORD,
        database=MYSQL_DATABASE,
    )
    try:
        src = sqlite_conn.cursor()
        dst = mysql_conn.cursor()
        missing = [t for t in TABLES if not src.execute(
            "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (t,)
        ).fetchone()]
        if missing:
            raise RuntimeError(f"Missing SQLite source tables: {missing}")

        # Preflight every destination table before inserting any records.
        for table in TABLES:
            dst.execute(f"SHOW TABLES LIKE %s", (table,))
            exists = dst.fetchone() is not None
            if exists:
                dst.execute(f"SELECT COUNT(*) FROM {quote_identifier(table)}")
                count = dst.fetchone()[0]
                if count:
                    raise RuntimeError(
                        f"Target table {table} already contains {count} rows. "
                        "No data was inserted. Use a fresh/empty target schema after backup."
                    )

        for table in TABLES:
            src.execute(f"PRAGMA table_info({quote_identifier(table)})")
            columns = src.fetchall()
            if not columns:
                raise RuntimeError(f"Could not inspect SQLite table {table}")
            col_defs = []
            pk_columns = []
            for _cid, name, declared_type, notnull, _default, pk in columns:
                definition = f"{quote_identifier(name)} {mysql_type(declared_type)}"
                if notnull:
                    definition += " NOT NULL"
                col_defs.append(definition)
                if pk:
                    pk_columns.append((pk, name))
            if pk_columns:
                pk_names = [quote_identifier(name) for _, name in sorted(pk_columns)]
                col_defs.append("PRIMARY KEY (" + ", ".join(pk_names) + ")")
            create_sql = (
                f"CREATE TABLE IF NOT EXISTS {quote_identifier(table)} ("
                + ", ".join(col_defs)
                + ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4"
            )
            dst.execute(create_sql)

            names = [c[1] for c in columns]
            select_sql = f"SELECT * FROM {quote_identifier(table)}"
            insert_sql = (
                f"INSERT INTO {quote_identifier(table)} ("
                + ", ".join(quote_identifier(n) for n in names)
                + ") VALUES ("
                + ", ".join(["%s"] * len(names))
                + ")"
            )
            src.execute(select_sql)
            inserted = 0
            while True:
                batch = src.fetchmany(BATCH_SIZE)
                if not batch:
                    break
                dst.executemany(insert_sql, batch)
                inserted += len(batch)
            print(f"{table}: inserted {inserted} rows")

        mysql_conn.commit()
        print("Migration committed. Run Infosys_MySQL_Analysis.sql for analysis and row-count checks.")
    except Exception:
        mysql_conn.rollback()
        raise
    finally:
        try:
            src.close()
            dst.close()
        except Exception:
            pass
        sqlite_conn.close()
        mysql_conn.close()


if __name__ == "__main__":
    main()
